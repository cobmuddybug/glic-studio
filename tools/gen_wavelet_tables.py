#!/usr/bin/env python3
"""Generate libglic/src/wavelet_tables.inc from the Java harness dump.

    build/java-harness/run.sh wavelets wavelets.txt
    tools/gen_wavelet_tables.py wavelets.txt > libglic/src/wavelet_tables.inc

The coefficients come straight out of the JWave jar GLIC ships (as Java hex
doubles), so the C++ tables are bit-identical by construction.
"""
import sys

entries = []
cur = None
for line in open(sys.argv[1]):
    if line.startswith("wavelet "):
        head, name = line.rstrip("\n").split(" name=", 1)
        parts = head.split()
        cur = {
            "id": int(parts[1]),
            "cls": parts[2],
            "mother": int(parts[3].split("=")[1]),
            "transform": int(parts[4].split("=")[1]),
            "name": name,
        }
        entries.append(cur)
    else:
        key, *vals = line.split()
        cur[key] = vals

print("// Generated by tools/gen_wavelet_tables.py from GLIC's JWave.jar. Do not edit.")
print("// JWave is MIT licensed, (c) Christian Scheiblich (see NOTICE.md).")
print()
for e in entries:
    for k in ("sd", "wd", "sr", "wr"):
        print(f"static const double w{e['id']}_{k}[] = {{{', '.join(e[k])}}};")
print()
print("static const WaveletDef kWavelets[] = {")
print('    {0, "NONE", 0, 0, false, nullptr, nullptr, nullptr, nullptr},')
for e in entries:
    halve = "true" if e["cls"].endswith(".Haar1Orthogonal") else "false"
    i = e["id"]
    print(f'    {{{i}, "{e["name"]}", {e["mother"]}, {e["transform"]}, {halve}, '
          f"w{i}_sd, w{i}_wd, w{i}_sr, w{i}_wr}},")
print("};")
